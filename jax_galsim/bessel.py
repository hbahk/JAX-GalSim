@jax.jit
def bessel_j0_root_approx(s):
    b = (s - 0.25) * jnp.pi
    temp = 1 / (8 * b)
    inv8bsq = temp**2

    b += temp
    temp *= (4.0 / 3.0) * inv8bsq
